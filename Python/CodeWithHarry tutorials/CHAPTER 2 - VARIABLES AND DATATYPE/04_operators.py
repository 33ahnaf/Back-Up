# Arthmatic Operators
a = 7
b = 4

c = a + b # Plus operator
d = a - b # Minus operator
e = a*b # Multiplication operator
f = a/b # Division operator
print(c)
print(d)
print(e)
print(f)

print("\n")

# Assignment Operators
a = 4-2 # Assign 4-2 in a
b = 6
print(a)
print(b)
a += 3 # Increase the value of a by 3
b -= 2 # Decrease the value of b by 2
print(a)
print(b)

print("\n")

# Comparison Operators
print(5 == 5)
print(5 == 6)

print(6 > 5)
print(5 > 6)

print(5 < 6)
print(6 < 5)

print(6 >= 6)
print(6 >= 5)
print(5 >= 6)

print(6 <= 6)
print(5 <= 6)
print(6 <= 5)

print(5 != 6)
print(5 != 5)

print("\n")

# Logical Operators
