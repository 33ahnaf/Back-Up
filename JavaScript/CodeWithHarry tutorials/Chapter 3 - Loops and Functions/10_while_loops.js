// while loop
let i = 0;
while (i < 100) {
    console.log("Count: ", i+1);
    i++;
}





// do-while loop
let j = 0;
do {
    console.log("Count: ", j+1);
    j++;
} while (j < 100);

// Note: needless to say, do-while loop runs minimum of 1 time(s) even if do-while loop's condition is hardcoded to false.